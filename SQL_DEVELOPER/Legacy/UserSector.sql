CREATE TABLE users (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id         NUMBER NOT NULL,
    username        VARCHAR2(100) UNIQUE NOT NULL,
    password_hash   VARCHAR2(255) NOT NULL,
    email           VARCHAR2(200) UNIQUE,
    balance         NUMBER(14,2) DEFAULT 0 CHECK (balance >= 0),
    trade_count     NUMBER DEFAULT 0 CHECK (trade_count >= 0),
    is_bot          CHAR(1) DEFAULT 'N' CHECK (is_bot IN ('Y','N')),
    is_banned       CHAR(1) DEFAULT 'N' CHECK (is_banned IN ('Y','N')),
    created_at      DATE DEFAULT SYSDATE,

    CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES roles(id)
);

CREATE INDEX idx_users_role ON users(role_id);
CREATE INDEX idx_users_isbot ON users(is_bot);
CREATE INDEX idx_users_isbanned ON users(is_banned);

CREATE TABLE portfolios (
    user_id         NUMBER PRIMARY KEY,
    created_at      DATE DEFAULT SYSDATE,
    last_updated_at DATE DEFAULT SYSDATE,

    CONSTRAINT fk_portfolio_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE achievements (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR2(100) UNIQUE NOT NULL,
    description     VARCHAR2(400),
    icon_path       VARCHAR2(255)
);
CREATE TABLE user_achievements (
    user_id         NUMBER NOT NULL,
    achievement_id  NUMBER NOT NULL,
    achieved_at     DATE DEFAULT SYSDATE,

    CONSTRAINT pk_user_achievements PRIMARY KEY (user_id, achievement_id),
    CONSTRAINT fk_user_ach_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_user_ach_ach FOREIGN KEY (achievement_id) REFERENCES achievements(id) ON DELETE CASCADE
);

CREATE INDEX idx_user_ach_user ON user_achievements(user_id);

CREATE TABLE upgrades (
    id                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_upgrade_id   NUMBER,
    name                VARCHAR2(100) NOT NULL,
    description         VARCHAR2(400),
    tier                NUMBER(3) DEFAULT 1 CHECK (tier >= 1),
    branch              VARCHAR2(50),
    icon_path           VARCHAR2(255),

    CONSTRAINT fk_upgrades_parent FOREIGN KEY (parent_upgrade_id) REFERENCES upgrades(id)
);

CREATE INDEX idx_upgrades_branch ON upgrades(branch);
CREATE INDEX idx_upgrades_tier ON upgrades(tier);

CREATE TABLE user_upgrades (
    user_id         NUMBER NOT NULL,
    upgrade_id      NUMBER NOT NULL,
    acquired_at     DATE DEFAULT SYSDATE,

    CONSTRAINT pk_user_upgrades PRIMARY KEY (user_id, upgrade_id),
    CONSTRAINT fk_user_up_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_user_up_upgrade FOREIGN KEY (upgrade_id) REFERENCES upgrades(id) ON DELETE CASCADE
);

