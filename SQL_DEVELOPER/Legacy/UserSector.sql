CREATE TABLE orders_active (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_id        NUMBER NOT NULL,
    user_id         NUMBER NOT NULL,
    trade_id        NUMBER,
    created_at      DATE DEFAULT SYSDATE,
    order_type      VARCHAR2(10) CHECK (order_type IN ('BUY', 'SELL')),
    price           NUMBER(14,2) CHECK (price >= 0),
    quantity        NUMBER(10) CHECK (quantity > 0),
    is_active       CHAR(1) DEFAULT 'Y' CHECK (is_active IN ('Y', 'N')),

    CONSTRAINT fk_order_stock FOREIGN KEY (stock_id) REFERENCES stocks(id),
    CONSTRAINT fk_order_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE INDEX idx_orders_active_user ON orders_active(user_id);
CREATE INDEX idx_orders_active_stock ON orders_active(stock_id);
CREATE INDEX idx_orders_active_type ON orders_active(order_type);
CREATE INDEX idx_orders_active_status ON orders_active(is_active);

CREATE TABLE orders_history (
    id              NUMBER PRIMARY KEY,
    stock_id        NUMBER NOT NULL,
    user_id         NUMBER NOT NULL,
    trade_id        NUMBER,
    created_at      DATE,
    closed_at       DATE DEFAULT SYSDATE,
    order_type      VARCHAR2(10) CHECK (order_type IN ('BUY', 'SELL')),
    price           NUMBER(14,2),
    quantity        NUMBER(10),
    status          VARCHAR2(15) CHECK (status IN ('TRADED','CANCELLED')),

    CONSTRAINT fk_orderhist_stock FOREIGN KEY (stock_id) REFERENCES stocks(id),
    CONSTRAINT fk_orderhist_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE INDEX idx_orders_hist_user ON orders_history(user_id);
CREATE INDEX idx_orders_hist_stock ON orders_history(stock_id);
CREATE INDEX idx_orders_hist_status ON orders_history(status);