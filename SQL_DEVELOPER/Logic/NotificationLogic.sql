-- 10. NOTIFICATIONS
-- Хранит сами уведомления (содержание и тип)
CREATE TABLE NOTIFICATIONS (
    notification_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    title           VARCHAR2(200),
    message         VARCHAR2(1000),
    type            VARCHAR2(20) CHECK (type IN ('INFO', 'SUCCESS', 'WARNING', 'ERROR', 'TRADE')),
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP
);

-- 11. USER_NOTIFICATIONS
-- Хранит статус прочтения для конкретного пользователя
CREATE TABLE USER_NOTIFICATIONS (
    user_id         NUMBER REFERENCES users(user_id) ON DELETE CASCADE,
    notification_id NUMBER REFERENCES notifications(notification_id) ON DELETE CASCADE,
    is_read         NUMBER(1) DEFAULT 0 CHECK (is_read IN (0, 1)),
    delivered_at    TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT pk_user_notif PRIMARY KEY (user_id, notification_id)
);


CREATE OR REPLACE PACKAGE pkg_notifications AS

    -- Создать личное уведомление (для одного юзера)
    PROCEDURE create_personal_notification (
